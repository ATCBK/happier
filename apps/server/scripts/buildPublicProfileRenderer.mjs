import { build } from 'esbuild';
import { copyFile, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createPublicRendererProtocolSourcePlugin } from './publicRendererProtocolSource.mjs';

const defaultProjectDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Bind the actual portable page to the server's declared RNW renderer, without an app runtime. */
export async function buildPublicProfileRenderer({ projectDir = defaultProjectDir, check = false, printPatch = false } = {}) {
    const requireServer = createRequire(resolve(projectDir, 'package.json'));
    const sourceDir = resolve(projectDir, 'sources/app/account/profile/render');
    const target = resolve(sourceDir, 'publicProfileRenderer.generated.mjs');
    // One RNW instance: the page's StyleSheet rules and the sheet the renderer serializes must be the same module.
    const reactNativeWeb = requireServer.resolve('react-native-web/dist/index.js');
    const result = await build({
        absWorkingDir: projectDir, entryPoints: [resolve(sourceDir, 'publicProfileRenderer.ts')],
        bundle: true, write: false, minify: true, platform: 'node', format: 'esm', target: ['node20'], jsx: 'automatic',
        tsconfig: resolve(projectDir, 'tsconfig.json'), conditions: ['happier-source'],
        external: ['react', 'react-dom/server', 'react/jsx-runtime'],
        alias: {
            'react-native': reactNativeWeb,
            'react-native-web': reactNativeWeb,
            'react-native-svg': requireServer.resolve('react-native-svg/lib/module/elements.web.js'),
        },
        define: { 'process.env.NODE_ENV': '"production"', '__DEV__': 'false' },
        legalComments: 'eof',
        plugins: [createPublicRendererProtocolSourcePlugin(projectDir)],
    });
    const source = '// Generated by scripts/buildPublicProfileRenderer.mjs; do not edit.\n' + result.outputFiles[0].text;
    if (printPatch) {
        // stdout is a generator transport for remote execution, not runtime code.
        process.stdout.write(`*** Begin Patch\n*** Add File: ${target}\n${source.replace(/\n$/u, '').split('\n').map(line => '+' + line).join('\n')}\n*** End Patch\n`);
        return;
    }
    if (check) {
        if (await readFile(target, 'utf8') !== source) throw new Error('Public-profile renderer is stale; run build:public-profile');
    } else await writeFile(target, source);
}

/** One physical input list owns font staging and source-bundle capture. */
export async function readPublicProfileAssetFiles({ projectDir = defaultProjectDir } = {}) {
    const interRoot = resolve(projectDir, '../ui/sources/assets/fonts');
    const source = resolve(projectDir, 'assets/public-profile');
    return [
        ...['Inter-Regular.ttf', 'Inter-Medium.ttf', 'Inter-SemiBold.ttf'].map(filename => ({ filename, sourcePath: resolve(interRoot, filename) })),
        ...(await readdir(source)).map(filename => ({ filename, sourcePath: resolve(source, filename) })),
    ];
}

/** Retain the exact shipped faces and licenses, without a runtime source-tree dependency. */
export async function stagePublicProfileAssets({ projectDir = defaultProjectDir, outDir }) {
    const target = resolve(outDir, 'assets/public-profile');
    await mkdir(target, { recursive: true });
    const files = await readPublicProfileAssetFiles({ projectDir });
    for (const { filename, sourcePath } of files) await copyFile(sourcePath, resolve(target, filename));
    return files.map(({ filename }) => resolve(target, filename));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    await buildPublicProfileRenderer({ check: process.argv.includes('--check'), printPatch: process.argv.includes('--print-patch') });
}
