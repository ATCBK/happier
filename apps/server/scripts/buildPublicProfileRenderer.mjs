import { build } from 'esbuild';
import { copyFile, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const defaultProjectDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Bind the actual portable page to the server's declared RNW renderer, without an app runtime. */
export async function buildPublicProfileRenderer({ projectDir = defaultProjectDir, check = false } = {}) {
    const sourceDir = resolve(projectDir, 'sources/app/account/profile/render');
    const target = resolve(sourceDir, 'publicProfileRenderer.generated.mjs');
    const result = await build({
        absWorkingDir: projectDir, entryPoints: [resolve(sourceDir, 'publicProfileRenderer.ts')],
        bundle: true, write: false, minify: true, platform: 'node', format: 'esm', target: ['node20'], jsx: 'automatic',
        tsconfig: resolve(projectDir, 'tsconfig.json'), conditions: ['happier-source'],
        external: ['react', 'react-dom/server', 'react/jsx-runtime'],
        nodePaths: [resolve(projectDir, 'node_modules')],
        alias: {
            'react-native': resolve(projectDir, 'node_modules/react-native-web/dist/index.js'),
            'react-native-svg': resolve(projectDir, 'node_modules/react-native-svg/lib/module/elements.web.js'),
        },
        define: { 'process.env.NODE_ENV': '"production"', '__DEV__': 'false' },
        legalComments: 'eof',
    });
    const source = '// Generated by scripts/buildPublicProfileRenderer.mjs; do not edit.\n' + result.outputFiles[0].text;
    if (check) {
        if (await readFile(target, 'utf8') !== source) throw new Error('Public-profile renderer is stale; run build:public-profile');
    } else await writeFile(target, source);
}

/** The runtime bundle resolves local faces next to its entry/chunks, never through the UI source tree. */
export async function stagePublicProfileAssets({ projectDir = defaultProjectDir, outDir }) {
    const target = resolve(outDir, 'assets/public-profile');
    await mkdir(target, { recursive: true });
    const interRoot = resolve(projectDir, '../ui/sources/assets/fonts');
    for (const file of ['Inter-Regular.ttf', 'Inter-Medium.ttf', 'Inter-SemiBold.ttf']) {
        await copyFile(resolve(interRoot, file), resolve(target, file));
    }
    const source = resolve(projectDir, 'assets/public-profile');
    for (const file of await readdir(source)) await copyFile(resolve(source, file), resolve(target, file));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    await buildPublicProfileRenderer({ check: process.argv.includes('--check') });
}
