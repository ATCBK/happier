import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Authoring-time Fontconfig metadata only. Builds and server runtime consume the
// checked-in table and never spawn fc-query or inspect host font directories.
const faces = {
    regular: '../../ui/sources/assets/fonts/Inter-Regular.ttf',
    medium: '../../ui/sources/assets/fonts/Inter-Medium.ttf',
    semiBold: '../../ui/sources/assets/fonts/Inter-SemiBold.ttf',
    cjk: '../assets/public-profile/NotoSansCJKsc-Regular.otf',
    arabic: '../assets/public-profile/NotoSansArabic-Regular.ttf',
    emoji: '../assets/public-profile/NotoEmoji[wght].ttf',
};
const coverage = Object.fromEntries(Object.entries(faces).map(([face, relative]) => {
    const path = fileURLToPath(new URL(relative, import.meta.url));
    const charset = execFileSync('fc-query', ['--format', '%{charset}\n', path], { encoding: 'utf8' });
    const intervals = [...new Set(charset.trim().split(/\s+/u))].map(token => {
        const [first, last = first] = token.split('-');
        return [Number.parseInt(first, 16), Number.parseInt(last, 16)];
    }).sort((a, b) => a[0] - b[0]);
    if (intervals.length === 0 || intervals.some(range => range.some(value => !Number.isFinite(value)))) {
        throw new Error(`Invalid shipped font coverage: ${face}`);
    }
    return [face, intervals];
}));
const families = Object.fromEntries(Object.entries(faces).map(([face, relative]) => {
    const path = fileURLToPath(new URL(relative, import.meta.url));
    const family = execFileSync('fc-query', ['--format', '%{family}\n', path], { encoding: 'utf8' })
        .trim().split('\n')[0].split(',').at(-1);
    if (!family) throw new Error(`Invalid shipped font family: ${face}`);
    return [face, family];
}));
const output = fileURLToPath(new URL('../sources/app/account/profile/render/publicProfileFontCoverage.generated.ts', import.meta.url));
writeFileSync(output, '// Generated by scripts/generatePublicProfileFontCoverage.mjs from the exact shipped fonts.\n'
    + 'export const PUBLIC_PROFILE_FONT_FAMILIES = ' + JSON.stringify(families) + ' as const;\n'
    + 'export const PUBLIC_PROFILE_FONT_COVERAGE: Readonly<Record<keyof typeof PUBLIC_PROFILE_FONT_FAMILIES, readonly (readonly [number, number])[]>> = '
    + JSON.stringify(coverage) + ';\n');
