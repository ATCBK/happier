import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { buildUiSourceAsset } from '../sourceAsset.mjs';

const ui = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const core = resolve(ui, '../../packages/brand/atmosphere.mjs');

async function writeChanged(file, contents) {
    const previous = await readFile(file, 'utf8').catch(error => {
        if (error.code === 'ENOENT') return null;
        throw error;
    });
    if (previous !== contents) {
        await mkdir(dirname(file), { recursive: true });
        await writeFile(file, contents);
    }
}

/** One source producer owns both targets, before or after workspace dist exists. */
export async function buildAtmosphereRenderers({ outputDirectory, web = true, uiDirectory = ui, retainLastGreen = false } = {}) {
    const nativeFile = outputDirectory ? resolve(outputDirectory, 'backdropWorkletCore.generated.js')
        : resolve(uiDirectory, 'sources/components/atmosphere/backdropWorkletCore.generated.js');
    const workerFile = outputDirectory ? resolve(outputDirectory, 'happier-atmosphere-worker.js')
        : resolve(uiDirectory, 'public/happier-atmosphere-worker.js');
    const built = await buildUiSourceAsset({ outputs: web ? [nativeFile, workerFile] : [nativeFile],
        retainLastGreen, build: async () => {
        const native = await build({ stdin: { contents: `export { renderBackdrop, cropOf, backdropBandGrade, atmosphereRipple, createAtmosphereTransition, orderedFade } from ${JSON.stringify(core)};`,
            resolveDir: ui, sourcefile: 'atmosphere-worklet-entry.js' }, bundle: true, platform: 'neutral',
            format: 'iife', globalName: 'AtmosphereWorkletCore', target: 'es2020', write: false });
        // Worklets need this generated lexical closure on their secondary runtime.
        let worker;
        if (web) {
            worker = await build({ entryPoints: [resolve(uiDirectory, 'sources/components/atmosphere/atmosphere.worker.ts')],
                alias: { '@happier-dev/brand/atmosphere': core }, bundle: true, platform: 'browser', format: 'iife',
                target: 'es2020', write: false, minify: true });
        }
        // Compile both targets before replacing either retained output.
        await writeChanged(nativeFile, `// Generated by tools/atmosphere/buildAtmosphereRenderers.mjs.\nexport function createAtmosphereWorkletCore() {\n'worklet';\n${native.outputFiles[0].text}\nreturn AtmosphereWorkletCore;\n}\n`);
        if (worker) await writeChanged(workerFile, worker.outputFiles[0].text);
        return { nativeFile, workerFile };
    } });
    return { nativeFile, workerFile, ...built };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await buildAtmosphereRenderers();
