import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const entryRelative = 'sources/components/ui/media/pdf/pdfWebViewEntry.ts';
const outputRelative = 'sources/components/ui/media/pdf/pdfjsWebViewBundle.generated.ts';

export async function createPdfjsWebViewBundleSource({ expoAppDir }) {
    const { build } = await import('esbuild');
    const require = createRequire(path.join(expoAppDir, 'package.json'));
    const worker = await fs.readFile(require.resolve('pdfjs-dist/legacy/build/pdf.worker.min.mjs'), 'utf8');
    const result = await build({
        absWorkingDir: expoAppDir, entryPoints: [entryRelative], bundle: true, write: false,
        format: 'iife', platform: 'browser', target: ['es2020'], minify: true, legalComments: 'none',
        define: { __PDFJS_WORKER_SOURCE__: JSON.stringify(worker) },
        // This private native document runtime needs the canonical pure presentation
        // functions it reaches, not React/React Native's complete presentation barrel.
        alias: {
            '@happier-dev/plugin-ui/presentation': path.resolve(expoAppDir, 'tools/pdfjs/pluginUiPresentationPure.ts'),
            '@/scm/utils/filePresentation': path.resolve(expoAppDir, 'sources/scm/utils/filePresentation.ts'),
            '@happier-dev/protocol/crypto/base64': path.resolve(expoAppDir, '../../packages/protocol/src/crypto/base64.ts'),
        },
    });
    const js = result.outputFiles[0]?.text;
    if (!js || !js.includes('__pdfAppend')) throw new Error('Invalid native PDF bundle');
    const bundleBytes = Buffer.byteLength(js);
    // Chunk literals for the native JavaScript parser; this is not a document transport size.
    const chunks = [];
    for (let offset = 0; offset < js.length; offset += 50_000) chunks.push(js.slice(offset, offset + 50_000));
    const contents = `/** Generated by tools/pdfjs/buildPdfjsWebViewBundle.mjs; no runtime network fallback. */\n`
        + `export const PDFJS_WEBVIEW_BUNDLE_JS = [\n${chunks.map(chunk => `    ${JSON.stringify(chunk)},`).join('\n')}\n].join('');\n`
        + `export const PDFJS_WEBVIEW_BUNDLE_BYTES = ${bundleBytes};\n`;
    return { contents, bundleBytes };
}

export async function buildPdfjsWebViewBundle({ expoAppDir }) {
    const { contents, bundleBytes } = await createPdfjsWebViewBundleSource({ expoAppDir });
    const outFile = path.join(expoAppDir, outputRelative);
    const previous = await fs.readFile(outFile, 'utf8').catch(() => null);
    if (previous !== contents) await fs.writeFile(outFile, contents);
    return { outFile, bundleBytes, wrote: previous !== contents };
}

export async function verifyPdfjsWebViewBundle({ expoAppDir }) {
    const expected = await createPdfjsWebViewBundleSource({ expoAppDir });
    const outFile = path.join(expoAppDir, outputRelative);
    if (await fs.readFile(outFile, 'utf8').catch(() => null) !== expected.contents) {
        throw new Error(`Native PDF bundle is missing or stale: ${outFile}; regenerate with the PDF bundle producer`);
    }
    return { outFile, bundleBytes: expected.bundleBytes };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const expoAppDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
    const check = process.argv.includes('--check');
    const result = await (check ? verifyPdfjsWebViewBundle : buildPdfjsWebViewBundle)({ expoAppDir });
    console.log(`[pdfjs] native bundle ${check ? 'verified' : 'prepared'}: ${result.bundleBytes} bytes`);
}
